"""Regenerate the word lists `apps/quality/readability.py` reads (rarely, by hand; the output is committed).

Needs NLTK's cmudict (baked into the image) and wordfreq, which is not a project dependency:

    docker compose run --rm --no-deps -T web sh -c "pip install --quiet --target /tmp/wf wordfreq==3.1.1 \
        && PYTHONPATH=/tmp/wf python -m apps.quality.data.build_wordlists"

- syllables.tsv: CMU Pronouncing Dictionary syllable counts (first pronunciation) for the words where they
  differ from the skill's vowel-group heuristic, so the file stays small and the heuristic covers the rest.
- frequent-words.txt: the 5,000 most frequent English words, as Yoast's word-complexity rule uses.
"""

import re
from pathlib import Path

from apps.quality.readability import heuristic_syllables

HERE = Path(__file__).parent


def build_syllables():
    from nltk.corpus import cmudict

    rows = []
    for word, pronunciations in sorted(cmudict.dict().items()):
        if not re.fullmatch(r"[a-z]+(?:'[a-z]+)?", word):
            continue
        count = sum(phone[-1].isdigit() for phone in pronunciations[0])
        if count and count != heuristic_syllables(word):
            rows.append(f"{word}\t{count}")
    header = (
        "# Syllable counts from the CMU Pronouncing Dictionary (Carnegie Mellon University, BSD-style\n"
        "# licence, via NLTK's cmudict corpus), only where they differ from the vowel-group heuristic.\n"
        "# Generated by build_wordlists.py; do not edit by hand.\n"
    )
    (HERE / "syllables.tsv").write_text(header + "\n".join(rows) + "\n", encoding="utf-8")
    return len(rows)


def build_frequent(limit=5000):
    from wordfreq import top_n_list

    found = []
    for word in top_n_list("en", 20000):
        if re.fullmatch(r"[a-z]+(?:'[a-z]+)?", word) and word not in found:
            found.append(word)
        if len(found) == limit:
            break
    header = (
        "# The 5,000 most frequent English words, from wordfreq 3.1.1 (Robyn Speer; data CC BY-SA 4.0,\n"
        "# https://github.com/rspeer/wordfreq). Generated by build_wordlists.py; do not edit by hand.\n"
    )
    (HERE / "frequent-words.txt").write_text(header + "\n".join(found) + "\n", encoding="utf-8")
    return len(found)


if __name__ == "__main__":
    print("syllables:", build_syllables())
    print("frequent words:", build_frequent())
